"""The A6h freeze must stay exactly what it claims to be.

`SECOND-ROUND.md` said the HEAD_B mutation is registered at step 0, before
any provider sees the candidate. That was unachievable in the order it
described: provider exposure begins at `pull_request.opened`, and A6g
watched CodeRabbit comment on `#32` six seconds after it opened. So the
mutation is frozen here, before the branch exists, and these tests are what
stop the freeze drifting into a description of itself.
"""
import hashlib
import subprocess
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent.parent
FREEZE = HERE / "a6h-freeze"
sys.path.insert(0, str(FREEZE))
sys.path.insert(0, str(FREEZE / "specimen" / "governor" / "pilot"))

import verify  # noqa: E402

#: Exactly what the freeze may contain. A build artifact swept in by a test
#: run would otherwise be frozen as part of the specimen — `.pyc` bytes vary
#: by interpreter, so the freeze would stop being reproducible while still
#: looking authoritative.
EXPECTED = {
    "specimen": {"governor/pilot/a6h_probe.py",
                 "governor/pilot/test_a6h_probe.py"},
    "mutation": {"governor/pilot/a6h-head-move.txt"},
}
BASE_SHA = "047ff1a641e33e0bb8c6b9eea26bb80eea021e08"


def test_the_freeze_holds_exactly_the_declared_files():
    manifest = verify.manifest()
    for kind, expected in EXPECTED.items():
        assert set(manifest[kind]) == expected, kind


def test_generated_bytecode_cannot_enter_the_manifest():
    """A pytest run inside the specimen directory swept `.pytest_cache` and
    a `.pyc` into the first manifest. Interpreter-dependent bytes would have
    made the freeze unreproducible while still looking authoritative, so
    generated files are excluded by construction — and only those."""
    pilot = FREEZE / "specimen" / "governor" / "pilot"
    (pilot / "__pycache__").mkdir(exist_ok=True)
    (pilot / "__pycache__" / "a6h_probe.cpython-999.pyc").write_bytes(b"\x00")
    try:
        assert set(verify.manifest()["specimen"]) == EXPECTED["specimen"]
    finally:
        import shutil
        shutil.rmtree(pilot / "__pycache__")
    assert verify.GENERATED == ("__pycache__", ".pytest_cache")


def test_an_authored_stray_still_fails(tmp_path):
    """The exclusion is narrow: anything that is not generated bytecode and
    is not in the freeze is an UNFROZEN_EXTRA."""
    for rel in EXPECTED["specimen"]:
        dst = tmp_path / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes((FREEZE / "specimen" / rel).read_bytes())
    (tmp_path / "governor/pilot/notes.md").write_text("smuggled\n")
    out = verify.check("specimen", tmp_path)
    assert out["matches_freeze"] is False
    assert any(f["state"] == "UNFROZEN_EXTRA" for f in out["files"])


def test_the_document_quotes_the_digests_it_freezes():
    """A digest in prose that disagrees with the bytes is worse than none."""
    doc = (FREEZE / "FREEZE.md").read_text()
    manifest = verify.manifest()
    for kind, files in manifest.items():
        for rel, meta in files.items():
            assert meta["sha256"] in doc, f"{kind}/{rel}"
            assert f"{meta['bytes']} bytes" in doc, f"{kind}/{rel}"
    assert BASE_SHA in doc


def test_the_protocol_points_at_the_freeze_and_shares_its_base():
    protocol = (HERE / "SECOND-ROUND.md").read_text()
    assert "a6h-freeze" in protocol, \
        "the protocol must send a reader to the artifact that binds it"
    assert BASE_SHA in protocol and BASE_SHA in (FREEZE / "FREEZE.md").read_text()
    # The reordered step 0: freeze and remote readback precede the branch.
    for step in ("0a", "0b", "0c", "0d"):
        assert step in protocol


def test_a_candidate_matching_the_freeze_verifies(tmp_path):
    for rel in EXPECTED["specimen"]:
        dst = tmp_path / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes((FREEZE / "specimen" / rel).read_bytes())
    assert verify.check("specimen", tmp_path)["matches_freeze"] is True


@pytest.mark.parametrize("how", ["edited", "missing", "extra"])
def test_a_candidate_that_differs_is_refused(tmp_path, how):
    for rel in EXPECTED["specimen"]:
        dst = tmp_path / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes((FREEZE / "specimen" / rel).read_bytes())
    target = tmp_path / "governor/pilot/a6h_probe.py"
    if how == "edited":
        target.write_bytes(target.read_bytes() + b"\n# tweak\n")
    elif how == "missing":
        target.unlink()
    else:
        (tmp_path / "governor/pilot/extra.py").write_text("x = 1\n")
    out = verify.check("specimen", tmp_path)
    assert out["matches_freeze"] is False
    states = {f["state"] for f in out["files"]}
    assert states & {"DIFFERS", "MISSING", "UNFROZEN_EXTRA"}


def test_the_frozen_specimen_passes_its_own_frozen_suite(tmp_path):
    """Frozen and correct are different properties; this asserts both.

    Run against a copy. The first version ran pytest inside the freeze and
    left a `__pycache__` in the specimen tree — the very contamination the
    stray-artifact test exists to catch, produced by the test suite
    checking for it.
    """
    import os
    import shutil
    work = tmp_path / "pilot"
    shutil.copytree(FREEZE / "specimen" / "governor" / "pilot", work)
    env = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1"}
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider",
         str(work / "test_a6h_probe.py")],
        capture_output=True, text=True, cwd=str(work), env=env)
    assert proc.returncode == 0, proc.stdout[-2000:]
    assert " passed" in proc.stdout


def test_the_specimen_contract_is_the_one_reviewed():
    """Spot-check the behaviour the docstring promises, from this suite too,
    so a rewrite of the module cannot quietly change what was frozen."""
    from a6h_probe import expansion_words, word_size
    assert (word_size(0), word_size(1), word_size(32), word_size(33)) == (0, 1, 1, 2)
    assert word_size(2 ** 53 + 1) == (2 ** 53 + 1 + 31) // 32
    with pytest.raises(ValueError):
        word_size(-1)
    assert expansion_words(64, 32) == 0
    assert expansion_words(0, 33) == 2


def test_the_mutation_is_one_file_and_says_why_it_exists():
    body = (FREEZE / "mutation" / "governor" / "pilot" /
            "a6h-head-move.txt").read_text()
    assert len(EXPECTED["mutation"]) == 1
    flat = " ".join(body.split())
    assert "frozen in review-governance before the candidate branch existed" \
        in flat
    assert "confirmed SUCCESS on HEAD_A" in flat


def test_the_freeze_is_readable_before_anything_is_built():
    """No credential, no network, no repository state is needed to check it."""
    import inspect
    source = inspect.getsource(verify)
    for forbidden in ("requests", "urllib", "subprocess", "governor",
                      "installation_token"):
        assert forbidden not in source, forbidden
