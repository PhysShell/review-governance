#!/usr/bin/env python3
"""Check a candidate against the frozen specimen, byte for byte.

The freeze exists so that HEAD_A and the HEAD_B mutation are fixed before
the candidate branch exists — because provider exposure begins at
`pull_request.opened`, not at our request. A6g watched CodeRabbit comment on
`#32` six seconds after it opened, unprompted. Registering the mutation
"at step 0" therefore did not mean "before any provider saw the candidate",
and this artifact is what closes that gap.

Two things it can check:

    --specimen <dir>   the working tree that will become HEAD_A
    --mutation <dir>   the working tree that will become HEAD_B

Neither performs any network call, and neither writes anything.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


#: Generated bytecode is never authored and is interpreter-dependent, so it
#: is excluded by construction rather than by hoping nobody runs the tests
#: in place. The list is deliberately narrow and named: anything else that
#: appears in the tree is an UNFROZEN_EXTRA and fails.
GENERATED = ("__pycache__", ".pytest_cache")


def _is_generated(path: Path, root: Path) -> bool:
    parts = path.relative_to(root).parts
    return any(p in GENERATED for p in parts) or path.suffix == ".pyc"


def frozen(kind):
    """Every authored file under the frozen tree, path -> (bytes, digest)."""
    root = HERE / kind
    out = {}
    for p in sorted(root.rglob("*")):
        if p.is_file() and not _is_generated(p, root):
            data = p.read_bytes()
            out[str(p.relative_to(root))] = (data, digest(data))
    return out


def check(kind, target: Path):
    """Compare a candidate tree against the freeze. Reports, never repairs."""
    want = frozen(kind)
    results, ok = [], True
    for rel, (data, want_digest) in want.items():
        candidate = target / rel
        if not candidate.exists():
            results.append({"path": rel, "state": "MISSING"})
            ok = False
            continue
        got = digest(candidate.read_bytes())
        same = got == want_digest
        ok = ok and same
        results.append({"path": rel, "state": "MATCH" if same else "DIFFERS",
                        "expected_sha256": want_digest, "observed_sha256": got,
                        "bytes": len(data)})
    # A candidate carrying more than the freeze is not the frozen specimen.
    for p in sorted(target.rglob("*")):
        if p.is_file() and not _is_generated(p, target) \
                and str(p.relative_to(target)) not in want:
            results.append({"path": str(p.relative_to(target)),
                            "state": "UNFROZEN_EXTRA"})
            ok = False
    return {"kind": kind, "matches_freeze": ok, "files": results}


def manifest():
    return {kind: {rel: {"sha256": d, "bytes": len(b)}
                   for rel, (b, d) in frozen(kind).items()}
            for kind in ("specimen", "mutation")}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--specimen", type=Path)
    ap.add_argument("--mutation", type=Path)
    ap.add_argument("--manifest", action="store_true")
    args = ap.parse_args()
    out = {}
    if args.manifest or not (args.specimen or args.mutation):
        out["manifest"] = manifest()
    if args.specimen:
        out["specimen"] = check("specimen", args.specimen)
    if args.mutation:
        out["mutation"] = check("mutation", args.mutation)
    print(json.dumps(out, indent=2))
    checks = [v for k, v in out.items() if k in ("specimen", "mutation")]
    return 0 if all(c["matches_freeze"] for c in checks) else 1


if __name__ == "__main__":
    sys.exit(main())
